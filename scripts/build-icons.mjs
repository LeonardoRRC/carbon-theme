// Builds resources/icons from react-icons: one <pack>.json per icon set plus index.json.
//
//   npm i --no-save react-icons react react-dom
//   node scripts/build-icons.mjs [node_modules directory]
//
// Each pack file is { id, name, license, url, icons: { name: svg } }, where name is the
// component name in kebab-case without its pack prefix (LuHouse -> house). The SVGs are
// minified and drawn in black, so the Panel can embed them as CSS masks. index.json lists
// every pack's metadata and icon names, for searching across packs without loading SVGs.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const modules = path.resolve(process.argv[2] ?? 'node_modules');
const out = path.resolve('resources/icons');
const require = createRequire(path.join(modules, 'noop.js'));

const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const { IconsManifest } = require('react-icons/lib');
const version = JSON.parse(fs.readFileSync(path.join(modules, 'react-icons/package.json'), 'utf8')).version;

// Multicolor sets lose their colors as single-color masks.
const SKIP = new Set(['fc']);

const kebab = (value) =>
    value
        .replace(/([a-z])([A-Z0-9])/g, '$1-$2')
        .replace(/([0-9])([A-Za-z])/g, '$1-$2')
        .replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2')
        .toLowerCase();

function minify(svg) {
    return svg
        // Only the root's sizing goes; shapes such as <rect> need their own width and height.
        .replace(/^<svg[^>]*>/, (root) => root.replace(/\s(height|width|style|class)="[^"]*"/g, ''))
        .replace(/currentColor/g, '#000')
        .replace(/\s+/g, ' ')
        .replace(/\s+>/g, '>')
        .replace(/>\s+</g, '><')
        .trim();
}

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

const index = { source: 'react-icons', version, packs: [] };
for (const pack of IconsManifest) {
    if (SKIP.has(pack.id)) continue;

    const components = require(`react-icons/${pack.id}`);
    const prefix = pack.id.replace(/\d+$/, '');
    const icons = {};
    let duplicates = 0;
    for (const [component, Icon] of Object.entries(components)) {
        if (typeof Icon !== 'function') continue;
        const bare = component.toLowerCase().startsWith(prefix) ? component.slice(prefix.length) : component;
        const name = kebab(bare);
        if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) continue;
        if (icons[name]) {
            duplicates++;
            continue;
        }
        icons[name] = minify(renderToStaticMarkup(React.createElement(Icon)));
    }

    const data = { id: pack.id, name: pack.name, license: pack.license, url: pack.projectUrl, icons };
    fs.writeFileSync(path.join(out, `${pack.id}.json`), JSON.stringify(data));
    index.packs.push({ id: pack.id, name: pack.name, license: pack.license, url: pack.projectUrl, licenseUrl: pack.licenseUrl, names: Object.keys(icons) });
    console.log(`${pack.id}: ${Object.keys(icons).length} icons${duplicates ? ` (${duplicates} duplicate names skipped)` : ''}`);
}

fs.writeFileSync(path.join(out, 'index.json'), JSON.stringify(index));

// Several sets require attribution (CC BY, CC BY-SA), so every set's license ships with them.
const licenses = [
    '# Icon licenses',
    '',
    `The icon sets in this folder are generated by \`scripts/build-icons.mjs\` from [react-icons](https://react-icons.github.io/react-icons/) ${version} (MIT). The SVGs are minified and drawn in a single color; the drawings are unchanged. Each set keeps its own license:`,
    '',
    '| Set | License | Project |',
    '| --- | --- | --- |',
    ...index.packs.map((p) => `| ${p.name} (\`${p.id}\`) | [${p.license}](${p.licenseUrl}) | ${p.url} |`),
    '',
    'Simple Icons are brand logos; the brands remain trademarks of their owners.',
    '',
];
fs.writeFileSync(path.join(out, 'LICENSES.md'), licenses.join('\n'));
console.log(`react-icons ${version}: ${index.packs.length} packs, ${index.packs.reduce((n, p) => n + p.names.length, 0)} icons`);
